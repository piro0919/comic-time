/**
 * 作品の突き合わせと、作品ページの住所。
 *
 * 取得の script からも読むので、ここには別名解決の要る import を置かない。
 */

/**
 * 突き合わせのためにタイトルを揃える。
 * 全角半角（NFKC）と、波ダッシュ・全角チルダの違い、空白だけを吸収する。
 * 括弧の中身は落とさない。落とすと別作品を同じものとして扱ってしまう。
 */
export function titleKey(title: string): string {
  return title
    .normalize("NFKC")
    .replace(/[〜～]/g, "~")
    .replace(/\s+/g, "")
    .toLowerCase();
}

/**
 * 住所に使う長さの上限。文字数で数える。
 *
 * 書き出したページは題名そのままのファイルになる。Linux のファイル名は 255 バイトまでで、
 * 日本語は1文字3バイト、絵文字なら4バイト使う。拡張子のぶんも要るので、
 * いちばん重い字で埋まっても収まる長さにしておく。
 * macOS は文字数で数えるため、手元では溢れない。
 */
const maxLength = 50;

/**
 * 作品ページの住所のもと。日本語はそのまま残す。
 * 住所やサイトマップで意味が変わってしまう字だけを落とす。
 * 角括弧は Next の動的な区間と同じ形なので、これも落とす。
 *
 * 落としたり切ったりした結果ぶつかることがあるので、実際に配る住所は台帳側で重なりを見て決める。
 * 一度配った住所は台帳に残り、題名の表記が直っても変わらない。
 */
export default function workSlug(title: string): string {
  const slug = titleKey(title).replace(/["#%&'+/<>?[\\\]^`{|}]/g, "");

  // 絵文字のような組で1文字の字を、途中で割らない
  return slug === "" ? "work" : [...slug].slice(0, maxLength).join("");
}
